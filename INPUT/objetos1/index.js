// construye una carta (cada propiedad en su propia etiqueta) para un personaje
function crearCarta(personaje) {
  const card = document.createElement("div");
  card.className = "card";

  const imgEl = document.createElement("img");
  imgEl.className = "card-imagen";
  imgEl.src = personaje.imagen;
  imgEl.alt = personaje.nombre;
  card.appendChild(imgEl);

  const body = document.createElement("div");
  body.className = "card-body";
  card.appendChild(body);

  const header = document.createElement("div");
  header.className = "card-header";
  body.appendChild(header);

  const nombreEl = document.createElement("h2");
  nombreEl.className = "card-nombre";
  nombreEl.textContent = personaje.nombre;
  header.appendChild(nombreEl);

  const subtitle = document.createElement("p");
  subtitle.className = "card-subtitle";
  header.appendChild(subtitle);

  const bandoEl = document.createElement("span");
  bandoEl.className = "card-bando " + personaje.bando;
  bandoEl.textContent = personaje.bando;
  subtitle.appendChild(bandoEl);
  subtitle.appendChild(document.createTextNode(" · "));

  const universoEl = document.createElement("span");
  universoEl.className = "card-universo";
  universoEl.textContent = personaje.universo;
  subtitle.appendChild(universoEl);

  const stats = document.createElement("div");
  stats.className = "card-stats";
  body.appendChild(stats);

  function agregarStat(etiqueta, valor, claseExtra) {
    const stat = document.createElement("div");
    stat.className = "stat";

    const labelEl = document.createElement("span");
    labelEl.className = "stat-label";
    labelEl.textContent = etiqueta;

    const valueEl = document.createElement("span");
    valueEl.className = claseExtra ? "stat-value " + claseExtra : "stat-value";
    valueEl.textContent = valor;

    stat.appendChild(labelEl);
    stat.appendChild(valueEl);
    stats.appendChild(stat);
  }

  agregarStat("Edad", personaje.edad);
  agregarStat("Altura", personaje.altura + " m");
  agregarStat("Fuerza", personaje.nivelDeFuerza);
  agregarStat("Activo", personaje.activo ? "Sí" : "No", personaje.activo ? "activo-si" : "activo-no");

  const descripcionEl = document.createElement("p");
  descripcionEl.className = "card-descripcion";
  descripcionEl.textContent = personaje.descripcion;
  body.appendChild(descripcionEl);

  const poderesWrapper = document.createElement("div");
  body.appendChild(poderesWrapper);

  const poderesTitulo = document.createElement("p");
  poderesTitulo.className = "card-poderes-titulo";
  poderesTitulo.textContent = "Poderes";
  poderesWrapper.appendChild(poderesTitulo);

  const listaPoderes = document.createElement("ul");
  listaPoderes.className = "card-poderes";
  personaje.poder.forEach(function (p) {
    const li = document.createElement("li");
    li.textContent = p;
    listaPoderes.appendChild(li);
  });
  poderesWrapper.appendChild(listaPoderes);

  return card;
}

const galeria = document.getElementById("galeria");
heroes.forEach(function (personaje) {
  galeria.appendChild(crearCarta(personaje));
});

// botón de modo oscuro
const btnDark = document.getElementById("btn-dark");
btnDark.addEventListener("click", function () {
  document.body.classList.toggle("dark-mode");
  btnDark.textContent = document.body.classList.contains("dark-mode")
    ? "☀️ Modo Claro"
    : "🌙 Modo Oscuro";
});
