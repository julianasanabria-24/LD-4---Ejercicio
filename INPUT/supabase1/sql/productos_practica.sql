-- Crea la tabla productos_practica con datos de ejemplo.
-- Cómo usarlo: Supabase → SQL Editor → New query → pega todo esto → Run.

create table if not exists public.products_practice (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  nombre      text,
  descripcion text,
  precio      int8,      -- precio en pesos, número entero
  unidades    int8,      -- unidades en inventario
  descuento   float8,    -- fracción de 0 a 1 (0.15 = 15%)
  disponible  bool,
  categorias  json       -- array de categorías, ej. ["tecnología", "oferta"]
);

